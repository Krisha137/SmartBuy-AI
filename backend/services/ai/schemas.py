"""
AI Schema definitions and Backend Validation logic for SmartBuy AI.
"""

VALID_CATEGORIES = ["Laptop"]
VALID_USE_CASES = [
    "Programming", "Gaming", "Everyday", "Professional",
    "Design & Video", "Design & Video Editing",
    "Business & Office", "Business & Productivity",
    "Data Science & AI", "College & Everyday Use", "General"
]
VALID_STORAGE_TYPES = ["SSD", "HDD", "eMMC"]
VALID_PRIORITIES = ["low", "medium", "high"]
VALID_BRANDS = [
    "Acer", "Apple", "ASUS", "Dell", "HP", "Lenovo",
    "LG", "Microsoft", "MSI", "Razer", "Samsung"
]


def validate_parsed_requirements(parsed_data: dict) -> tuple[dict, list[str]]:
    """
    Validates and sanitizes requirement structure generated by AI or NLP parser.
    Returns (sanitized_dict, errors_list).
    """
    errors = []
    if not isinstance(parsed_data, dict):
        return {}, ["Parsed output must be a valid JSON object."]

    sanitized = {
        "status": "clear",
        "requirements": {
            "category": "Laptop",
            "budget_min": None,
            "budget_max": None,
            "use_case": None,
            "minimum_ram": None,
            "minimum_storage": None,
            "preferred_storage_type": None,
            "battery_priority": None,
            "performance_priority": None,
            "weight_priority": None,
            "brand_preference": None
        },
        "unsupported_requirements": [],
        "clarification_questions": []
    }

    # Validate status
    status = parsed_data.get("status", "clear")
    if status not in ["clear", "needs_clarification"]:
        errors.append(f"Invalid status '{status}'. Must be 'clear' or 'needs_clarification'.")
    else:
        sanitized["status"] = status

    # Validate requirements dict
    reqs = parsed_data.get("requirements", {})
    if not isinstance(reqs, dict):
        reqs = {}

    # Category
    cat = reqs.get("category", "Laptop")
    if cat and cat not in VALID_CATEGORIES:
        errors.append(f"Unsupported product category '{cat}'. SmartBuy AI currently supports MVP category 'Laptop'.")
    else:
        sanitized["requirements"]["category"] = "Laptop"

    # Budget Min
    b_min = reqs.get("budget_min")
    if b_min is not None:
        try:
            b_min_val = int(round(float(b_min)))
            if b_min_val < 0:
                errors.append("budget_min cannot be negative.")
            else:
                sanitized["requirements"]["budget_min"] = b_min_val
        except (ValueError, TypeError):
            errors.append("budget_min must be a valid numeric value.")

    # Budget Max
    b_max = reqs.get("budget_max")
    if b_max is not None:
        try:
            b_max_val = int(round(float(b_max)))
            if b_max_val < 0:
                errors.append("budget_max cannot be negative.")
            else:
                sanitized["requirements"]["budget_max"] = b_max_val
        except (ValueError, TypeError):
            errors.append("budget_max must be a valid numeric value.")

    # Validate Budget Range
    s_min = sanitized["requirements"]["budget_min"]
    s_max = sanitized["requirements"]["budget_max"]
    if s_min is not None and s_max is not None and s_min > s_max:
        errors.append(f"Invalid budget range: budget_min (₹{s_min:,}) cannot be greater than budget_max (₹{s_max:,}).")

    # Use Case
    use_case = reqs.get("use_case")
    if use_case:
        match = next((uc for uc in VALID_USE_CASES if uc.lower() == str(use_case).lower()), None)
        if not match:
            errors.append(f"Invalid use_case '{use_case}'. Must be one of {VALID_USE_CASES}.")
        else:
            sanitized["requirements"]["use_case"] = match

    # Minimum RAM
    ram = reqs.get("minimum_ram")
    if ram is not None:
        try:
            ram_val = int(ram)
            if ram_val <= 0:
                errors.append("minimum_ram must be greater than 0.")
            else:
                sanitized["requirements"]["minimum_ram"] = ram_val
        except (ValueError, TypeError):
            errors.append("minimum_ram must be a valid integer.")

    # Minimum Storage
    storage = reqs.get("minimum_storage")
    if storage is not None:
        try:
            storage_val = int(storage)
            if storage_val <= 0:
                errors.append("minimum_storage must be greater than 0.")
            else:
                sanitized["requirements"]["minimum_storage"] = storage_val
        except (ValueError, TypeError):
            errors.append("minimum_storage must be a valid integer.")

    # Preferred Storage Type
    st_type = reqs.get("preferred_storage_type")
    if st_type:
        match_st = next((st for st in VALID_STORAGE_TYPES if st.lower() == str(st_type).lower()), None)
        if not match_st:
            errors.append(f"Invalid preferred_storage_type '{st_type}'. Must be one of {VALID_STORAGE_TYPES}.")
        else:
            sanitized["requirements"]["preferred_storage_type"] = match_st

    # Priorities (battery, performance, weight)
    for p_field in ["battery_priority", "performance_priority", "weight_priority"]:
        p_val = reqs.get(p_field)
        if p_val:
            match_p = next((p for p in VALID_PRIORITIES if p.lower() == str(p_val).lower()), None)
            if not match_p:
                errors.append(f"Invalid {p_field} '{p_val}'. Must be one of {VALID_PRIORITIES}.")
            else:
                sanitized["requirements"][p_field] = match_p

    # Brand Preference
    brand = reqs.get("brand_preference")
    if brand:
        match_brand = next((b for b in VALID_BRANDS if b.lower() == str(brand).lower()), None)
        if match_brand:
            sanitized["requirements"]["brand_preference"] = match_brand
        else:
            # If brand is unsupported by dataset, move to unsupported_requirements
            sanitized["unsupported_requirements"].append(f"Brand '{brand}'")

    # Unsupported requirements
    unsupported = parsed_data.get("unsupported_requirements", [])
    if isinstance(unsupported, list):
        for item in unsupported:
            if isinstance(item, str) and item.strip():
                if item.strip() not in sanitized["unsupported_requirements"]:
                    sanitized["unsupported_requirements"].append(item.strip())

    # Clarification questions
    questions = parsed_data.get("clarification_questions", [])
    if isinstance(questions, list):
        for q in questions:
            if isinstance(q, str) and q.strip():
                sanitized["clarification_questions"].append(q.strip())

    return sanitized, errors
